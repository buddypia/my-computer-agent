#!/usr/bin/env node

/**
 * _cli-dispatch.mjs — Single universal multi-CLI hook dispatcher (R-CM-006 Rule 4 extension)
 *
 * Dynamically loads `run(data)` of the main hook → delegates to `runAdapter`. Replaces previous piles
 * of CLI-specific adapter files (`.claude/hooks/{codex,antigravity}/<name>.mjs`, ~17 lines boilerplate each)
 * with a single file — eliminating the porting toil of "creating adapter files for every hook".
 *
 * codegen (`cli-hooks-codegen.mjs#renderEntry`) generates the following commands for `.codex/hooks.json` / `.claude/hooks.json`:
 *   node "$(dirname "$(git rev-parse --path-format=absolute --git-common-dir || echo /nonexistent/nogit)")/.cli/_cli-dispatch.mjs" <module> <cli> [eventName] [hookId]
 *
 * That expression decides **which repository's dispatcher runs**, so it is a guard of its own — SSOT and
 * full rationale in `cli-hooks-codegen.mjs#REPO_ROOT_SHELL_EXPR`. In short: `--git-common-dir` keeps a
 * linked worktree from supplying its own guards, and `|| echo` keeps a git failure from resolving the
 * path to the cwd's `.cli/` (`dirname ""` is `.`). Note this file never sees that failure — the point of
 * the fallback is that node fails to load anything, so nothing below executes.
 *
 * Usage: node _cli-dispatch.mjs <module> <codex|antigravity> [eventName] [hookId]
 *   - module    : Module path relative to repo-root (e.g., `.cli/hooks/commit-guard.mjs`,
 *                 `.claude/hooks/task-context-injector.mjs`). Dispatcher resolves relative to repoRoot.
 *                 Allowed boundary: `.cli/` + `.claude/hooks/` + `.claude/scripts/` (1:1 with
 *                 paths generated by codegen `moduleToRepoRelativePath`) — other paths rejected via fail-open.
 *   - cli       : 'codex' | 'antigravity' (selects normalizePayload / wire transformation)
 *   - eventName : 'PreToolUse' | 'PostToolUse' | 'UserPromptSubmit' | 'SessionStart' | 'Stop'
 *                 (required for Antigravity wire transformation; ignored by Codex)
 *   - hookId    : Registry `entry.id` (Defect 6). Optional for backwards compatibility with hand-invoked
 *                 commands, but always supplied by codegen — `runAdapter` uses it to check
 *                 `harness-budget.json#stop_block_allowlist` before emitting a Stop/SubagentStop block.
 *                 Missing id on those events is treated as not-allowlisted (fail-safe downgrade).
 *
 * fail-open (R-CM-006 Rule 2): Missing args/module/run or escaping `.cli/` boundary exits with 0
 *           (does not block main flow).
 * Boundary: Perspective 1 (harness itself) — R-CM-028. When distributed externally via bundles
 *           like git-worktree-isolation, copying this single file + main hooks carries over all CLI adapters.
 *
 * @see .cli/lib/cli-adapter-utils.mjs (runAdapter — standard entry point for main delegation)
 * @see .cli/lib/cli-hooks-codegen.mjs (renderEntry — command codegen)
 */
import { fileURLToPath } from 'node:url';
import { resolve, sep } from 'node:path';
import { runAdapter } from './lib/cli-adapter-utils.mjs';
import { INHERITED_REPOSITORY_POINTERS } from './lib/utils.mjs';

async function main() {
  const [, , rawModule, cli, eventName, hookId] = process.argv;
  const mod = String(rawModule || '').trim();
  if (!mod || !mod.endsWith('.mjs') || !cli) process.exit(0);

  const cliDir = resolve(fileURLToPath(new URL('.', import.meta.url))); // .../.cli
  const repoRoot = resolve(cliDir, '..'); // repo root
  const target = resolve(repoRoot, mod); // module is repo-relative (.cli/hooks/X.mjs etc.)
  // Allowed boundary: `.cli/` + `.claude/hooks/` + `.claude/scripts/` (repo-tracked main hook homes) —
  // 1:1 with path set generated by codegen (`cli-hooks-codegen.mjs#moduleToRepoRelativePath`).
  // Other paths (including traversals) remain fail-open passthrough (defense).
  const allowedRoots = [cliDir, resolve(repoRoot, '.claude', 'hooks'), resolve(repoRoot, '.claude', 'scripts')];
  const inBounds = allowedRoots.some((root) => target === root || target.startsWith(root + sep));
  if (!inBounds) process.exit(0);

  // Set orchestrator flag before dynamic import: prevents standalone blocks of main hooks
  // (`if (!globalThis.__HOOK_ORCHESTRATOR__) safeHookMain(...)`) from executing as import side effects,
  // avoiding double consumption / execution of stdin. Dispatcher only calls run(), so standalone
  // entry is unnecessary (same pattern as orchestrator — code-reviewer finding defense).
  globalThis.__HOOK_ORCHESTRATOR__ = true;
  // For the same reason `safeHookMain`'s scrub never reaches the hook: every hook names its
  // repository by the payload cwd / `-C`, and a pointer the session exports would override both.
  for (const pointer of INHERITED_REPOSITORY_POINTERS) delete process.env[pointer];

  let run;
  try {
    ({ run } = await import(target));
  } catch {
    process.exit(0); // Main module load failure → fail-open
  }
  if (typeof run !== 'function') process.exit(0);

  // runAdapter executes reading stdin → normalizePayload → run → emit + process.exit (internal fail-open).
  await runAdapter(run, { cli, eventName, hookId });
}

main();
